"""Build the CTRL brand files from the three SVGs in assets/brand.

  python3 tools/brand/build.py

Writes:
  js/app/brand.js                 the mark, wordmark and lockup paths for canvas and WebGL (window.CtrlBrand)
  assets/brand/icons/*.png        favicon, apple-touch-icon, PWA icons (any and maskable)
  assets/brand/icons/favicon.svg  the same mark as an SVG favicon
The share image (assets/brand/og.png) is drawn by js/app/share-card.js; tools/brand/og.py saves it.
After a logo change, rerun this and paste the new paths into the i-ctrl symbols in index.html
(the script prints them).
"""
import re, json, pathlib, cairosvg
ROOT = pathlib.Path(__file__).resolve().parents[2]
B = ROOT / 'assets/brand'
CYAN = '#1ee0f0'
BLACK = '#0a0b0d'

def load(name):
    s = (B / f'{name}.svg').read_text()
    w, h = map(float, re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', s).groups())
    d = re.search(r' d="([^"]+)"', s).group(1)
    return {'w': w, 'h': h, 'd': d}

P = {k: load(n) for k, n in [('mark', 'ctrl-mark'), ('word', 'ctrl-word'), ('lockup', 'ctrl')]}

js = f"""// The CTRL logo (official, 28 Nov 2026) as path data, for canvas and WebGL: the wing mark, the
// italic wordmark and the full lockup (mark over wordmark). Generated by tools/brand/build.py from
// assets/brand/*.svg; the same paths are in the i-ctrl symbols in index.html for HTML.
//   CtrlBrand.draw(ctx, 'mark' | 'word' | 'lockup', x, y, height, colour) -> the width drawn
//   CtrlBrand.size('mark', height) -> {{ w, h }}
//   CtrlBrand.CYAN, CtrlBrand.BLACK   the brand's accent and matte black
// The logo is always one flat colour: white on dark, matte black on light. Never stretched or recoloured
// in parts.
window.CtrlBrand = (() => {{
  const P = {json.dumps(P, separators=(',', ':'))};
  const cache = {{}};
  const path = k => cache[k] || (cache[k] = new Path2D(P[k].d));
  const size = (k, h) => ({{ w: P[k].w * h / P[k].h, h }});
  function draw(ctx, k, x, y, h, color = '#fff') {{
    const s = h / P[k].h;
    ctx.save(); ctx.translate(x, y); ctx.scale(s, s); ctx.fillStyle = color; ctx.fill(path(k), 'evenodd'); ctx.restore();
    return P[k].w * s;
  }}
  return {{ P, draw, size, path, CYAN: '{CYAN}', BLACK: '{BLACK}' }};
}})();
"""
(ROOT / 'js/app/brand.js').write_text(js)

M = P['mark']
def icon_svg(size, pad, maskable=False, rx=None, strip=True):
    # matte black tile, the white wing mark centred, and three short cyan slashes low on the right
    # (the //// on the hoodie's shoulder); left off at favicon sizes, where they would be a smudge
    S = 512
    mh = S * (1 - 2 * pad)
    sc = mh / M['h']; mw = M['w'] * sc
    x = (S - mw) / 2 - S * 0.025; y = (S - mh) / 2
    r = rx if rx is not None else (0 if maskable else S * 0.18)
    k = 1 - 2 * pad
    bx, by, bw, bh = S * (0.5 + 0.30 * k), S * (0.5 + 0.43 * k), S * 0.026 * k / 0.6, S * 0.075 * k / 0.6
    bar = ''.join(f'<path d="M{bx + i * bw * 1.9:.1f} {by:.1f}l{bw:.1f} 0l{bh * 0.55:.1f} {-bh:.1f}l{-bw:.1f} 0z" fill="{CYAN}"/>' for i in range(3)) if strip else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{size}" height="{size}">'
            f'<rect width="{S}" height="{S}" rx="{r:.1f}" fill="{BLACK}"/>'
            f'<path fill="#fff" fill-rule="evenodd" transform="translate({x:.2f} {y:.2f}) scale({sc:.6f})" d="{M["d"]}"/>{bar}</svg>')

out = B / 'icons'; out.mkdir(exist_ok=True)
jobs = [
    ('favicon-32.png', 32, 0.12, False, None, False),
    ('favicon-48.png', 48, 0.12, False, None, False),
    ('apple-touch-icon.png', 180, 0.2, False, 0, True),   # iOS rounds the corners itself
    ('icon-192.png', 192, 0.2, False, None, True),
    ('icon-512.png', 512, 0.2, False, None, True),
    ('maskable-192.png', 192, 0.24, True, None, True),   # inside the 80% safe circle
    ('maskable-512.png', 512, 0.24, True, None, True),
]
for name, size, pad, mask, rx, strip in jobs:
    cairosvg.svg2png(bytestring=icon_svg(size, pad, mask, rx, strip).encode(), write_to=str(out / name), output_width=size, output_height=size)
(out / 'favicon.svg').write_text(icon_svg(64, 0.12, strip=False).replace(' width="64" height="64"', '') + '\n')
print('wrote js/app/brand.js and', len(jobs) + 1, 'icons')
print('mark viewBox 0 0 %g %g' % (M['w'], M['h']))
